// Regenerates the docs site's rule catalog from the built core package.
// Usage: pnpm build && node scripts/generate-rule-docs.mjs
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { listRuleCards, ruleSlug } from "../packages/core/dist/rules/registry.js";

const root = dirname(fileURLToPath(new URL("../package.json", import.meta.url)));
const out = join(root, "apps/docs/src/app/home/rules-content.ts");

const CATEGORY_ORDER = [
  "correctness",
  "performance",
  "maintainability",
  "security",
  "accessibility",
  "hygiene",
];

const rules = listRuleCards()
  .map((rule) => ({ ...rule, slug: ruleSlug(rule.id) }))
  .sort(
    (a, b) =>
      CATEGORY_ORDER.indexOf(a.category) - CATEGORY_ORDER.indexOf(b.category) ||
      a.id.localeCompare(b.id),
  );

const body = `// Generated by scripts/generate-rule-docs.mjs from the @angular-doctor/core
// rule registry. Do not edit by hand; run \`pnpm build && node scripts/generate-rule-docs.mjs\`.

export interface RuleDoc {
  id: string;
  slug: string;
  title: string;
  summary: string;
  severity: string;
  category: string;
  docsUrl?: string;
  minAngular?: number;
}

export const ruleCategories = ${JSON.stringify(CATEGORY_ORDER, null, 2)} as const;

export const ruleCatalog: RuleDoc[] = ${JSON.stringify(
  rules.map((rule) => ({
    id: rule.id,
    slug: rule.slug,
    title: rule.title,
    summary: rule.summary ?? rule.title,
    severity: rule.defaultSeverity,
    category: rule.category,
    docsUrl: rule.docsUrl,
    minAngular: rule.minAngular,
  })),
  null,
  2,
)};
`;

writeFileSync(out, body, "utf8");
console.log(`Wrote ${rules.length} rules to ${out}`);
